#!/usr/bin/env node
// Builds doorstep/js/copy.js and the copy-review inventory from doorstep/copy/copy-en.json.
// Provenance is DERIVED from repository files, never hand-labelled:
//   R  = exact English match in a CCO-reviewed EN/MY pair (MY file named *reviewed*, or a sibling
//        provenance file naming CCO), docs/cco-*reviewed*.json, or dist/myanmar.js.
//   L  = exact English match in Myanmar that ships in main's dist/ or docs/ but is not in the reviewed set.
//   P  = no Myanmar exists. The app shows the English (lang="en") — never placeholder text as Myanmar.
// Usage: node doorstep/tools/build-copy.mjs   (run from the repository root; no dependencies)
import fs from 'node:fs'; import path from 'node:path'; import vm from 'node:vm';
const ROOT = process.cwd(); const D = p => path.join(ROOT, p);
const MY = /[က-႟]/;
const flat = (o, p = '', out = {}) => { if (o && typeof o === 'object') for (const [k, v] of Object.entries(o)) flat(v, p ? `${p}.${k}` : k, out); else if (typeof o === 'string') out[p] = o; return out; };
const walk = d => fs.readdirSync(d, { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);
const reviewed = new Map(), loose = new Map();
const add = (map, en, my, src) => { if (en && my && MY.test(my) && !MY.test(en) && !map.has(en)) map.set(en, { my, src: path.relative(ROOT, src) }); };

for (const f of walk(D('docs')).filter(f => f.endsWith('.json'))) {
  const b = path.basename(f); if (!b.includes('-my') || b.includes('initial')) continue;
  const prefix = b.split('-my')[0], dir = path.dirname(f), en = path.join(dir, prefix + '-en.json');
  if (!fs.existsSync(en)) continue;
  const prov = fs.readdirSync(dir).filter(x => x.includes('provenance') && (x.startsWith(prefix) || x === 'review-provenance.json'));
  const isReviewed = b.includes('reviewed') || prov.some(x => fs.readFileSync(path.join(dir, x), 'utf8').includes('CCO'));
  let E, M; try { E = flat(JSON.parse(fs.readFileSync(en, 'utf8'))); M = flat(JSON.parse(fs.readFileSync(f, 'utf8'))); } catch { continue; }
  for (const [k, v] of Object.entries(E)) add(isReviewed ? reviewed : loose, v, M[k], f);
}
for (const f of fs.readdirSync(D('docs')).filter(x => /^cco-.*reviewed.*\.json$/.test(x)))
  { const walkPairs = o => { if (o && typeof o === 'object') for (const [k, v] of Object.entries(o)) typeof v === 'string' ? add(reviewed, k, v, D('docs/' + f)) : walkPairs(v); };
    walkPairs(JSON.parse(fs.readFileSync(D('docs/' + f), 'utf8'))); }
const mjs = fs.readFileSync(D('dist/myanmar.js'), 'utf8');
for (const m of mjs.matchAll(/"((?:[^"\\]|\\.)*)"\s*:\s*"((?:[^"\\]|\\.)*)"/g)) add(reviewed, JSON.parse(`"${m[1]}"`), JSON.parse(`"${m[2]}"`), D('dist/myanmar.js'));
// loose: bilingual objects in shipped dist/*copy*.js
for (const f of fs.readdirSync(D('dist')).filter(x => /copy.*\.js$/.test(x))) {
  const sandbox = { window: {}, globalThis: {} }; sandbox.self = sandbox.window;
  try { vm.runInNewContext(fs.readFileSync(D('dist/' + f), 'utf8'), sandbox, { timeout: 500 }); } catch { continue; }
  for (const obj of [...Object.values(sandbox.window), ...Object.values(sandbox.globalThis)]) {
    if (!obj || typeof obj !== 'object' || !obj.en || !obj.my) continue;
    const E = flat(obj.en), M = flat(obj.my); for (const [k, v] of Object.entries(E)) add(loose, v, M[k], D('dist/' + f));
  }
}

{ const inh = D('doorstep/copy/inherited-my.json'); if (fs.existsSync(inh)) for (const [e, m] of Object.entries(JSON.parse(fs.readFileSync(inh, 'utf8')).pairs)) add(loose, e, m, inh); }
const en = JSON.parse(fs.readFileSync(D('doorstep/copy/copy-en.json'), 'utf8'));
const out = {}; const rows = []; const count = { R: 0, L: 0, P: 0 };
for (const [key, text] of Object.entries(en)) {
  let p = 'P', my = null, src = '';
  if (reviewed.has(text)) ({ my, src } = reviewed.get(text)), p = 'R';
  else if (loose.has(text)) ({ my, src } = loose.get(text)), p = 'L';
  out[key] = p === 'P' ? { en: text, p } : { en: text, my, p };
  count[p]++; rows.push({ key, en: text, my: my || '', p, src, review: p === 'R' ? 'no (unless meaning changes)' : 'yes — CCO' });
}
fs.writeFileSync(D('doorstep/js/copy.js'), `/* GENERATED by doorstep/tools/build-copy.mjs — do not edit by hand. R=${count.R} L=${count.L} P=${count.P} */\nwindow.LIFT_COPY=${JSON.stringify(out)};\n`);
const csv = s => `"${String(s).replace(/"/g, '""')}"`;
fs.writeFileSync(D('doorstep/copy/copy-review.csv'), '﻿key,english,myanmar_candidate,provenance,source,review_required\n' + rows.map(r => [r.key, r.en, r.my, r.p, r.src, r.review].map(csv).join(',')).join('\n') + '\n');
const md = [`# Doorstep copy-review inventory`, ``, `Generated from \`doorstep/copy/copy-en.json\` against the repository's reviewed copy. R=${count.R} · L=${count.L} · P=${count.P} (total ${rows.length}).`, ``,
  `- **R** — exact English match in CCO-reviewed source. Shown as Myanmar.`, `- **L** — Myanmar exists in main's shipped files but is not in the reviewed set. Shown as Myanmar; needs CCO confirmation before release.`, `- **P** — no Myanmar. The app shows the English with lang="en". Needs CCO authoring.`, ``,
  `| Key | English | Myanmar candidate | Prov. | Source | Review |`, `|---|---|---|---|---|---|`,
  ...rows.map(r => `| \`${r.key}\` | ${r.en.replace(/\|/g, '\\|')} | ${r.my.replace(/\|/g, '\\|')} | ${r.p} | ${r.src} | ${r.review} |`)].join('\n');
fs.writeFileSync(D('doorstep/copy/copy-review.md'), md + '\n');
console.log(`copy.js written · R=${count.R} L=${count.L} P=${count.P}`);
